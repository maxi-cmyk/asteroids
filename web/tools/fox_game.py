"""Ninefold for the game (nextSteps.md P2.1): every pose in fox_poses.py as a body cell and
nine tail cells (tails are its health, so each one is drawn on its own and can fall), at full
size and at 0.6 (the illusion), plus the pose tables the engine and renderer share:
    native/boss/fights/ninefold/poses.h   and   src/boss/ninefold/poses.mjs
Called by make-bosses.py rift(); both tables are generated, do not edit them by hand.
"""
import json
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from fox_pose import geometry, layers, pose  # noqa: E402
from fox_poses import POSES, SIT  # noqa: E402

WEB = Path(__file__).resolve().parents[1]
SMALL = 0.6   # the illusion's three foxes
# Poses the illusion's foxes use (the real one and the decoys, which have unlit eyes).
SMALL_POSES = ['sit', 'sit-blink', 'stand', 'rise', 'skid'] + [
    f'run-{t}{k}' for t in ('', 'up-', 'down-') for k in range(6)]
DECOY_POSES = ['sit', 'stand', 'rise', 'skid'] + [
    f'run-{t}{k}' for t in ('', 'up-', 'down-') for k in range(6)]
# Seated, the tails sway: the sit fan with the wave a little further on (the renderer cycles).
SWAY = [pose(**{**SIT, 'wave': w}) for w in (1.0, 2.0)]


def _key(g):
    return tuple(tuple(round(c) for c in q) for path in g['tail_paths'] for q in path[::5])


def build(sheet):
    names = list(POSES)
    sets, set_of = {}, {}
    tail_cells = {}

    def tail_set(p):
        g = geometry(p)
        k = _key(g)
        if k not in sets:
            sets[k] = len(sets)
            tail_cells[sets[k]] = p
        return sets[k]
    for name in names:
        set_of[name] = tail_set(POSES[name])
    sway = [tail_set(p) for p in SWAY]
    small_sets = {set_of[n] for n in SMALL_POSES} | set(sway)
    for sid, p in tail_cells.items():
        tails, _ = layers(p)
        for i, im in enumerate(tails):
            sheet.add(f'fox-t{sid}-{i}', im)
        if sid in small_sets:
            tails, _ = layers(p, SMALL)
            for i, im in enumerate(tails):
                sheet.add(f'fox-s-t{sid}-{i}', im)
    for name in names:
        p = POSES[name]
        sheet.add(f'fox-{name}', layers(p)[1])
        if name in SMALL_POSES:
            sheet.add(f'fox-s-{name}', layers(p, SMALL)[1])
        if name in DECOY_POSES:
            sheet.add(f'fox-sd-{name}', layers(p, SMALL, eyes_lit=False)[1])
    write_tables(names, set_of, sway)
    return len(sets)


def _enum(name):
    return 'FP_' + name.upper().replace('-', '_')


def _c(v):
    return '{' + ', '.join(_c(x) if isinstance(x, (list, tuple)) else f'{x:g}' for x in v) + '}'


def write_tables(names, set_of, sway):
    geo = [geometry(POSES[n]) for n in names]
    out = WEB / 'native/boss/fights/ninefold/poses.h'
    out.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        '#pragma once',
        '// Ninefold\'s poses: generated by tools/fox_game.py from tools/fox_poses.py (do not edit).',
        '// Offsets from the fox\'s centre at full size, facing left: each tail\'s hit point, the',
        '// forehead mark, the jaw, and the head and body circles (x, y, r).',
        'enum {',
        *[f'    {_enum(n)},' for n in names],
        '    FP_COUNT',
        '};',
        f'static const float FOX_POSE_TAIL[FP_COUNT][9][2] = {_c([g["tails"] for g in geo])};',
        f'static const float FOX_POSE_MARK[FP_COUNT][2] = {_c([g["mark"] for g in geo])};',
        f'static const float FOX_POSE_JAW[FP_COUNT][2] = {_c([g["jaw"] for g in geo])};',
        f'static const float FOX_POSE_HEAD[FP_COUNT][3] = {_c([g["head"] for g in geo])};',
        f'static const float FOX_POSE_BODY[FP_COUNT][3] = {_c([g["body"] for g in geo])};',
        '',
    ]
    out.write_text('\n'.join(lines))
    js = WEB / 'src/boss/ninefold/poses.mjs'
    js.parent.mkdir(parents=True, exist_ok=True)
    rows = [{'name': n, 'set': set_of[n], 'small': n in SMALL_POSES, 'decoy': n in DECOY_POSES,
             'tails': g['tails'], 'mark': g['mark'], 'jaw': g['jaw'], 'head': g['head'],
             'body': g['body']} for n, g in zip(names, geo)]
    js.write_text(
        "// Ninefold's poses: generated by tools/fox_game.py from tools/fox_poses.py (do not edit).\n"
        '// Indexed by the engine\'s FP_* ids (native/boss/fights/ninefold/poses.h); offsets from the\n'
        '// fox\'s centre at full size, facing left. `set` names its tail cells (fox-t{set}-{i}).\n'
        f'export const FOX_POSES = {json.dumps(rows, separators=(",", ":"))};\n'
        'export const FOX_POSE = Object.fromEntries(FOX_POSES.map((p, i) => [p.name, i]));\n'
        f'// The seated fan a little further through its sway, cycled by the renderer.\n'
        f'export const FOX_SWAY = {json.dumps(sway)};\n'
        'export const FOX_SMALL = 0.6;\n')
    _format(out, js)


def _format(c_file, js_file):
    """Leave the generated files in the repo's formats (clang-format, prettier) when installed."""
    cf = shutil.which('clang-format') or '/opt/homebrew/opt/llvm@22/bin/clang-format'
    if Path(cf).exists():
        subprocess.run([cf, '-i', str(c_file)], check=False)
    if shutil.which('npx'):
        subprocess.run(['npx', 'prettier', '--write', str(js_file)], cwd=WEB, check=False,
                       capture_output=True)
